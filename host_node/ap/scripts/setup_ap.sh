#!/usr/bin/env bash
# Bring up the STRATA guest Wi-Fi AP on a Raspberry Pi (Iteration 1).
#
# Prerequisites: Raspberry Pi OS (Bookworm+ recommended), Wi-Fi NIC, root.
# Usage (from repo root or anywhere):
#   sudo ./host_node/ap/scripts/setup_ap.sh
#
# This script does NOT start host_node, apply nftables strata rules, WireGuard,
# or captive-portal auth — those belong to later iterations. It only:
#   - validates AP_IFACE
#   - installs packages if missing
#   - renders hostapd + dnsmasq configs
#   - assigns AP_ADDRESS/AP_PREFIX on AP_IFACE
#   - starts hostapd + dnsmasq
#   - optionally enables lab NAT (ENABLE_LAB_NAT=true)

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
AP_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
# shellcheck source=lib.sh
source "${SCRIPT_DIR}/lib.sh"

if [[ "${EUID}" -ne 0 ]]; then
  echo "error: setup_ap.sh must run as root (sudo)" >&2
  exit 1
fi

ap_load_env "${AP_DIR}"
ap_require_passphrase
ap_iface_exists "${AP_IFACE}"

echo "== STRATA AP setup =="
echo "  AP_IFACE=${AP_IFACE}  WAN_IFACE=${WAN_IFACE}"
echo "  SSID=${SSID}  gateway=${AP_ADDRESS}/${AP_PREFIX}"
echo "  (WPA passphrase not logged)"

# --- packages ---
need_pkg=()
command -v hostapd >/dev/null 2>&1 || need_pkg+=(hostapd)
command -v dnsmasq >/dev/null 2>&1 || need_pkg+=(dnsmasq)
command -v iw >/dev/null 2>&1 || need_pkg+=(iw)
command -v rfkill >/dev/null 2>&1 || need_pkg+=(rfkill)
if ((${#need_pkg[@]})); then
  echo "installing packages: ${need_pkg[*]}"
  export DEBIAN_FRONTEND=noninteractive
  apt-get update -y
  apt-get install -y "${need_pkg[@]}"
fi

# Disable distro unit auto-start; we run with our generated configs.
systemctl disable --now hostapd 2>/dev/null || true
systemctl disable --now dnsmasq 2>/dev/null || true
systemctl mask hostapd 2>/dev/null || true
# dnsmasq left unmasked but stopped — we invoke it with an explicit conf.

rfkill unblock wifi || true

# Stop services that often claim wlan0 on Raspberry Pi OS.
if command -v nmcli >/dev/null 2>&1; then
  nmcli dev set "${AP_IFACE}" managed no 2>/dev/null || true
fi
# wpa_supplicant may hold the iface in client mode.
if systemctl is-active --quiet "wpa_supplicant@${AP_IFACE}" 2>/dev/null; then
  systemctl stop "wpa_supplicant@${AP_IFACE}" || true
fi
killall wpa_supplicant 2>/dev/null || true

mkdir -p "${GENERATED_DIR}"
chmod 755 /etc/strata 2>/dev/null || mkdir -p /etc/strata
ap_render_file "${AP_DIR}/templates/hostapd.conf.in" "${GENERATED_DIR}/hostapd.conf"
ap_render_file "${AP_DIR}/templates/dnsmasq.conf.in" "${GENERATED_DIR}/dnsmasq.conf"

# --- addressing ---
ip link set "${AP_IFACE}" down || true
ip addr flush dev "${AP_IFACE}" || true
ip link set "${AP_IFACE}" up
ip addr add "${AP_ADDRESS}/${AP_PREFIX}" dev "${AP_IFACE}"

# Persist a tiny helper so reboot operators know the expected address
# (actual reboot persistence of hostapd is via systemd units we install below).
cat > "${GENERATED_DIR}/network.env" <<EOF
# Generated by setup_ap.sh — do not commit.
AP_IFACE=${AP_IFACE}
WAN_IFACE=${WAN_IFACE}
AP_ADDRESS=${AP_ADDRESS}
AP_PREFIX=${AP_PREFIX}
SSID=${SSID}
EOF
chmod 644 "${GENERATED_DIR}/network.env"

# --- systemd units (project-owned, point at generated confs) ---
cat > /etc/systemd/system/strata-hostapd.service <<EOF
[Unit]
Description=STRATA hostapd (guest AP)
After=network.target
Wants=network.target

[Service]
Type=simple
ExecStart=/usr/sbin/hostapd ${GENERATED_DIR}/hostapd.conf
Restart=on-failure
RestartSec=2

[Install]
WantedBy=multi-user.target
EOF

cat > /etc/systemd/system/strata-dnsmasq.service <<EOF
[Unit]
Description=STRATA dnsmasq (guest DHCP/DNS)
After=strata-hostapd.service
Requires=strata-hostapd.service

[Service]
Type=simple
ExecStart=/usr/sbin/dnsmasq -k --conf-file=${GENERATED_DIR}/dnsmasq.conf
Restart=on-failure
RestartSec=2

[Install]
WantedBy=multi-user.target
EOF

systemctl daemon-reload
systemctl enable strata-hostapd.service strata-dnsmasq.service
systemctl restart strata-hostapd.service
systemctl restart strata-dnsmasq.service

# --- optional lab NAT (not the production nftables path) ---
if [[ "${ENABLE_LAB_NAT}" == "true" ]]; then
  echo "ENABLE_LAB_NAT=true — enabling ip_forward + iptables MASQUERADE on ${WAN_IFACE}"
  echo "warn: when you later run host_node with the strata nftables ruleset,"
  echo "      set ENABLE_LAB_NAT=false and re-run teardown/setup, or flush this NAT."
  sysctl -w net.ipv4.ip_forward=1 >/dev/null
  if ! iptables -t nat -C POSTROUTING -o "${WAN_IFACE}" -j MASQUERADE 2>/dev/null; then
    iptables -t nat -A POSTROUTING -o "${WAN_IFACE}" -j MASQUERADE
  fi
  if ! iptables -C FORWARD -i "${AP_IFACE}" -o "${WAN_IFACE}" -j ACCEPT 2>/dev/null; then
    iptables -A FORWARD -i "${AP_IFACE}" -o "${WAN_IFACE}" -j ACCEPT
  fi
  if ! iptables -C FORWARD -i "${WAN_IFACE}" -o "${AP_IFACE}" -m state --state RELATED,ESTABLISHED -j ACCEPT 2>/dev/null; then
    iptables -A FORWARD -i "${WAN_IFACE}" -o "${AP_IFACE}" -m state --state RELATED,ESTABLISHED -j ACCEPT
  fi
else
  echo "ENABLE_LAB_NAT=false — clients get DHCP and can reach ${AP_ADDRESS};"
  echo "  internet egress for guests is expected via host_node nftables later."
fi

echo
echo "AP is up."
echo "  Next: sudo ${SCRIPT_DIR}/verify_ap.sh"
echo "  Host node should use GUEST_IFACE=${AP_IFACE} and listen on ${AP_ADDRESS}:8080"
echo "  Flutter default HOST_API_URL=http://192.168.50.1:8080 (keep AP_ADDRESS in sync)"
